DO $$
DECLARE leftover TEXT;
BEGIN
  SELECT string_agg(DISTINCT v, ', ') INTO leftover FROM (
    SELECT "jurisdiction" AS v FROM "waqfs" WHERE "jurisdiction" IS NOT NULL AND "jurisdiction" NOT IN (SELECT code FROM jurisdiction_codes)
    UNION ALL
    SELECT "jurisdiction" AS v FROM "foundations" WHERE "jurisdiction" IS NOT NULL AND "jurisdiction" NOT IN (SELECT code FROM jurisdiction_codes)
    UNION ALL
    SELECT "jurisdiction" AS v FROM "counterparties" WHERE "jurisdiction" IS NOT NULL AND "jurisdiction" NOT IN (SELECT code FROM jurisdiction_codes)
    UNION ALL
    SELECT "jurisdiction" AS v FROM "trustee_licenses" WHERE "jurisdiction" IS NOT NULL AND "jurisdiction" NOT IN (SELECT code FROM jurisdiction_codes)
    UNION ALL
    SELECT "jurisdiction" AS v FROM "compliance_policy_sets" WHERE "jurisdiction" IS NOT NULL AND "jurisdiction" NOT IN (SELECT code FROM jurisdiction_codes)
    UNION ALL
    SELECT "jurisdiction" AS v FROM "vaults" WHERE "jurisdiction" IS NOT NULL AND "jurisdiction" NOT IN (SELECT code FROM jurisdiction_codes)
  ) unmapped;
  IF leftover IS NOT NULL THEN
    RAISE EXCEPTION 'Jurisdictions that are not a known country: %. Fix them by hand, then rerun.', leftover;
  END IF;
END $$;

